import os, re, sys, urllib.parse
sys.path.insert(0, os.path.dirname(__file__)); from map import MAT, MUI
base = os.path.join(os.path.dirname(__file__), 'node_modules/@tabler/icons/icons')
def svg(n):
    for st in ('filled', 'outline'):
        p = f'{base}/{st}/{n}.svg'
        if os.path.exists(p):
            s = open(p).read()
            s = re.sub(r'<!--.*?-->', '', s, flags=re.S); s = re.sub(r'\s*class="[^"]*"', '', s); s = re.sub(r'\s+', ' ', s).strip()
            s = s.replace('currentColor', '#000')
            s = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', '', s)
            s = re.sub(r'\s*(width|height)="24"', '', s)
            return s
enc = lambda s: s.replace('%','%25').replace('#','%23').replace('<','%3C').replace('>','%3E').replace('"',"'")
names = sorted(set(MAT.values()) | set(MUI.values()))
var = lambda n: '--ti-' + n
out = ['/* ================= Tabler icons (filled where available) — generated by tabler/gen.py ================= */', ':root {']
for n in names:
    out.append(f'  {var(n)}: url("data:image/svg+xml,{enc(svg(n))}");')
out.append('}')
# legacy font icons (Jellyfin draws them via ::before with a code point)
sel = ', '.join(f'.material-icons.{k}::before' for k in sorted(MAT))
out.append(sel + ' { content: "" !important; display: inline-block; width: 1em; height: 1em; vertical-align: top; background-color: currentColor;'
           ' -webkit-mask: no-repeat center / 92% auto; mask: no-repeat center / 92% auto; }')
for k, v in sorted(MAT.items()):
    out.append(f'.material-icons.{k}::before {{ -webkit-mask-image: var({var(v)}); mask-image: var({var(v)}); }}')
# MUI SvgIcons (header, drawer, toolbars)
sel = ', '.join(f'svg.MuiSvgIcon-root[data-testid="{k}Icon"]' for k in sorted(MUI))
out.append(sel + ' { background-color: currentColor; -webkit-mask: no-repeat center / 92% auto; mask: no-repeat center / 92% auto; }')
out.append(', '.join(f'svg.MuiSvgIcon-root[data-testid="{k}Icon"] > *' for k in sorted(MUI)) + ' { display: none; }')
for k, v in sorted(MUI.items()):
    out.append(f'svg.MuiSvgIcon-root[data-testid="{k}Icon"] {{ -webkit-mask-image: var({var(v)}); mask-image: var({var(v)}); }}')
sys.stdout.write('\n'.join(out) + '\n')
