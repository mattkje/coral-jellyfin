#!/usr/bin/env python3
"""Generates src/holiday.css (snow layers, Christmas lights, Santa hat). Deterministic: same output every run."""
import random, os
rnd = random.Random(1225)
enc = lambda s: s.replace('%', '%25').replace('#', '%23').replace('<', '%3C').replace('>', '%3E').replace('"', "'")

def snow(tile, n, rmin, rmax, amin, amax):
    out = []
    for _ in range(n):
        x, y = rnd.randint(0, tile), rnd.randint(0, tile)
        r = round(rnd.uniform(rmin, rmax), 1); a = round(rnd.uniform(amin, amax), 2)
        out.append(f'radial-gradient({r}px {r}px at {x}px {y}px, rgba(255,255,255,{a}) 50%, transparent 100%)')
    return ',\n    '.join(out)

near = snow(560, 22, 2.2, 3.6, .55, .9)   # big, fast, bright
far = snow(380, 34, 1.1, 2.0, .35, .65)   # small, slow, dim

# light string: sagging wire + 4 bulbs per 120px tile, each bulb twinkles on its own beat
colors = ['#ff5a4e', '#ffd166', '#5fd38d', '#6fb6ff']
bulbs = ''
for i, (x, c) in enumerate(zip([15, 45, 75, 105], colors)):
    y = 10 if i % 2 == 0 else 9
    begin = [0, 1.1, .5, 1.6][i]
    bulbs += (f'<g><circle cx="{x}" cy="{y+11}" r="9" fill="{c}" opacity=".55" filter="url(#b)">'
              f'<animate attributeName="opacity" values=".7;.15;.7" dur="2.2s" begin="{begin}s" repeatCount="indefinite"/></circle>'
              f'<rect x="{x-2.2}" y="{y}" width="4.4" height="4" rx="1" fill="#2a2522"/>'
              f'<ellipse cx="{x}" cy="{y+10}" rx="4.2" ry="6.4" fill="{c}">'
              f'<animate attributeName="opacity" values="1;.45;1" dur="2.2s" begin="{begin}s" repeatCount="indefinite"/></ellipse>'
              f'<ellipse cx="{x-1.3}" cy="{y+7.5}" rx="1.1" ry="2" fill="#fff" opacity=".55"/></g>')
lights = (f'<svg xmlns="http://www.w3.org/2000/svg" width="120" height="40" viewBox="0 0 120 40">'
          f'<defs><filter id="b" x="-1" y="-1" width="3" height="3"><feGaussianBlur stdDeviation="3.2"/></filter></defs>'
          f'<path d="M0 6 Q15 13 30 6 T60 6 T90 6 T120 6" fill="none" stroke="#1d1a18" stroke-width="1.6"/>{bulbs}</svg>')

hat = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 26">'
       '<path d="M4 20 C8 8 16 2 24 4 C27 5 29 9 28 13 C25 10 21 9 18 11 C15 13 13 17 12 21 Z" fill="#e2483d"/>'
       '<rect x="2" y="18" width="20" height="6" rx="3" fill="#fff4ee"/><circle cx="28.5" cy="14" r="3.4" fill="#fff4ee"/></svg>')

css = f"""/* ================= Holiday layer (1 Dec – 2 Jan) — generated by tools/gen-holiday.py ================= */
/* warm, cozy glow */
html, .backgroundContainer, .ui-corner-all, .wizardStartForm {{
  background-image:
    radial-gradient(1200px 500px at 50% 115%, rgba(255 150 70 / .16), transparent 70%),
    radial-gradient(900px 600px at 0% -10%, rgba(226 72 61 / .14), transparent 60%),
    radial-gradient(900px 600px at 100% -10%, rgba(255 196 120 / .08), transparent 60%) !important;
}}

/* snow: two fixed layers behind the content */
.backgroundContainer {{ overflow: hidden; }}
.backgroundContainer::before, .backgroundContainer::after {{
  content: ""; position: absolute; left: -10%; right: -10%; pointer-events: none; will-change: transform;
}}
.backgroundContainer::before {{
  top: -560px; height: calc(100% + 560px); background-size: 560px 560px;
  background-image:
    {near};
  animation: coral-snow-near 14s linear infinite;
}}
.backgroundContainer::after {{
  top: -380px; height: calc(100% + 380px); background-size: 380px 380px; filter: blur(.4px);
  background-image:
    {far};
  animation: coral-snow-far 22s linear infinite;
}}
@keyframes coral-snow-near {{ from {{ transform: translate3d(0, 0, 0); }} to {{ transform: translate3d(70px, 560px, 0); }} }}
@keyframes coral-snow-far  {{ from {{ transform: translate3d(0, 0, 0); }} to {{ transform: translate3d(-40px, 380px, 0); }} }}

/* string of lights under the top bar */
.MuiAppBar-root::after {{
  content: ""; position: absolute; left: 0; right: 0; bottom: -22px; height: 30px; pointer-events: none; z-index: 1;
  background: url("data:image/svg+xml,{enc(lights)}") repeat-x 0 0 / 90px 30px;
}}
/* give the lights room above the first heading (detail pages and sign-in have their own spacing) */
.mainAnimatedPage:not(.itemDetailPage):not(#loginPage) {{ margin-top: 16px; }}
.MuiAppBar-root {{ overflow: visible !important; }}

/* Santa hat on the header logo */
.MuiAppBar-root .MuiButton-startIcon:has(img[src*="icon-transparent"]) {{ position: relative; overflow: visible; }}
.MuiAppBar-root .MuiButton-startIcon:has(img[src*="icon-transparent"])::after {{
  content: ""; position: absolute; width: 17px; height: 14px; top: -9px; left: 7px; transform: rotate(-12deg);
  background: url("data:image/svg+xml,{enc(hat)}") center / contain no-repeat; pointer-events: none;
}}

/* sign-in greeting */
#loginPage:not(.hide) h1::after {{
  content: "Happy holidays"; display: block; margin-top: .35em; font-size: .95rem; font-weight: 600;
  color: var(--coral-light); letter-spacing: .02em;
}}

/* frosty touch on cards when hovered */
@media (hover: hover) {{
  .card:hover .cardScalable {{ box-shadow: 0 12px 30px rgba(0,0,0,.5), 0 0 0 2px rgba(var(--coral-rgb) / .85), 0 0 22px rgba(255 210 160 / .25) !important; }}
}}

/* calm: no snow or lights while a video plays, or for people who prefer less motion */
body:has(.videoPlayerContainer:not(.hide)) .backgroundContainer::before,
body:has(.videoPlayerContainer:not(.hide)) .backgroundContainer::after,
body:has(.videoPlayerContainer:not(.hide)) .MuiAppBar-root::after {{ display: none; }}
@media (prefers-reduced-motion: reduce) {{
  .backgroundContainer::before, .backgroundContainer::after {{ animation: none; }}
}}
"""
out = os.path.join(os.path.dirname(__file__), '..', 'src', 'holiday.css')
open(out, 'w').write(css)
print('wrote', os.path.relpath(out), len(css), 'bytes')
